//! Percent-encoding for one URL path segment (RFC 3986 unreserved set).
//! Deliberately not the `url` crate: a backend needs segment encoding,
//! nothing else.

/// Encode `s` as a single path segment: `/` is encoded, unreserved
/// characters and a few safe sub-delims pass through.
pub fn encode_segment(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for &b in s.as_bytes() {
        match b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                out.push(b as char)
            }
            _ => {
                out.push('%');
                out.push_str(&format!("{b:02X}"));
            }
        }
    }
    out
}

/// Encode a slash-separated relative path, segment by segment.
pub fn encode_path(path: &str) -> String {
    path.split('/')
        .map(encode_segment)
        .collect::<Vec<_>>()
        .join("/")
}

/// Encode one `application/x-www-form-urlencoded` value: unreserved
/// characters pass through, space becomes `+`, everything else is
/// `%XX` (uppercase hex).
pub fn encode_form(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for &b in s.as_bytes() {
        match b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                out.push(b as char)
            }
            b' ' => out.push('+'),
            _ => {
                out.push('%');
                out.push_str(&format!("{b:02X}"));
            }
        }
    }
    out
}
